#!/bin/zsh
# Builds OTPBar.app with swiftc (no Xcode / SwiftPM needed).
#   ./build.sh            build to build/OTPBar.app
#   ./build.sh --test     run the TOTP self-tests and the missing-translation check
#   ./build.sh --icons    redraw the app / menu bar icons, then build
#   ./build.sh --install  build and copy to /Applications, then launch
set -euo pipefail
cd "$(dirname "$0")"

APP=build/OTPBar.app
VERSION=1.0.0
mkdir -p .build build

SWIFTC_FLAGS=(-O -swift-version 5 -target "$(uname -m)-apple-macos13.0")

# Some Command Line Tools installs ship a stale usr/include/swift/module.modulemap that
# redefines SwiftBridging and breaks every build. Mask it with an empty file via a VFS overlay.
STALE=/Library/Developer/CommandLineTools/usr/include/swift/module.modulemap
if [[ -f $STALE && -f ${STALE:h}/bridging.modulemap ]] && grep -q "module SwiftBridging" $STALE; then
  : > .build/empty.modulemap
  cat > .build/vfs.yaml <<EOF
{ "version": 0, "case-sensitive": "false", "roots": [
  { "type": "file", "name": "$STALE", "external-contents": "$PWD/.build/empty.modulemap" } ] }
EOF
  SWIFTC_FLAGS+=(-vfsoverlay .build/vfs.yaml -Xcc -ivfsoverlay -Xcc .build/vfs.yaml)
fi

if [[ ${1:-} == --test ]]; then
  swiftc "${SWIFTC_FLAGS[@]}" Sources/OTPCore/*.swift Sources/otp-selftest/main.swift -o .build/otp-selftest
  .build/otp-selftest
  exec python3 tools/check-i18n.py
fi

if [[ ${1:-} == --icons || ! -f Resources/AppIcon.icns || ! -f Resources/MenuBarIcon.png ]]; then
  echo "› Drawing icons…"
  swiftc "${SWIFTC_FLAGS[@]}" tools/make-icons.swift -o .build/make-icons
  rm -rf .build/icons
  .build/make-icons .build/icons
  mkdir -p Resources
  iconutil -c icns .build/icons/AppIcon.iconset -o Resources/AppIcon.icns
  cp .build/icons/MenuBarIcon.png Resources/
fi

echo "› Compiling…"
rm -rf $APP
mkdir -p $APP/Contents/MacOS $APP/Contents/Resources
swiftc "${SWIFTC_FLAGS[@]}" -parse-as-library Sources/OTPCore/*.swift Sources/OTPBar/*.swift \
  -o $APP/Contents/MacOS/OTPBar

# Icons are generated by tools/make-icons.swift; run ./build.sh --icons to redraw them.
cp Resources/AppIcon.icns Resources/MenuBarIcon.png $APP/Contents/Resources/
cp -R Resources/*.lproj $APP/Contents/Resources/

cat > $APP/Contents/Info.plist <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>OTPBar</string>
  <key>CFBundleDisplayName</key><string>OTPBar</string>
  <key>CFBundleIdentifier</key><string>local.otpbar.OTPBar</string>
  <key>CFBundleExecutable</key><string>OTPBar</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundleDevelopmentRegion</key><string>en</string>
  <key>CFBundleLocalizations</key><array><string>en</string><string>zh-Hans</string></array>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>$VERSION</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>LSMinimumSystemVersion</key><string>13.0</string>
  <key>LSUIElement</key><true/>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSHumanReadableCopyright</key><string>OTPBar</string>
</dict>
</plist>
EOF

echo "› Signing (ad-hoc)…"
codesign --force --sign - $APP

echo "✓ Built $APP"

if [[ ${1:-} == --install ]]; then
  pkill -x OTPBar 2>/dev/null || true
  rm -rf /Applications/OTPBar.app
  cp -R $APP /Applications/
  open /Applications/OTPBar.app
  echo "✓ Installed to /Applications/OTPBar.app"
fi
